/**
  * @brief  Function implementing the defaultTask thread.
  * @param  argument: Not used
  * @retval None
  */
/* USER CODE END Header_StartDefaultTask */
void StartDefaultTask(void const * argument)
{
  /* USER CODE BEGIN 5 */

  // HEARTBEAT: If the board is alive, the LED will blink immediately
  for(int i=0; i<10; i++) {
      HAL_GPIO_TogglePin(GPIOA, GPIO_PIN_5);
      HAL_Delay(100);
  }

  rmw_uros_set_custom_transport(
    true, (void *) &huart2,
    cubemx_transport_open, cubemx_transport_close,
    cubemx_transport_write, cubemx_transport_read
  );


  allocator = rcutils_get_zero_initialized_allocator();
  allocator.allocate = microros_allocate;
  allocator.deallocate = microros_deallocate;
  allocator.reallocate = microros_reallocate;
  allocator.zero_allocate = microros_zero_allocate;
  rcutils_set_default_allocator(&allocator);

  // If the agent is not running, the code will STOP here
  if (rclc_support_init(&support, 0, NULL, &allocator) != RCL_RET_OK) {
      Error_Handler();
  }

  rclc_node_init_default(&node, "stm32_node", "", &support);
  rclc_publisher_init_default(&publisher, &node,
      ROSIDL_GET_MSG_TYPE_SUPPORT(std_msgs, msg, Int32), "stm32_publisher");

  msg.data = 0;

  for(;;)
  {
    if (rcl_publish(&publisher, &msg, NULL) == RCL_RET_OK) {
        msg.data++;
    }
    HAL_GPIO_TogglePin(GPIOA, GPIO_PIN_5); // Toggle every second
    osDelay(1000);
  }
  /* USER CODE END 5 */
}

